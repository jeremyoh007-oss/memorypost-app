// Usage: EXPO_PUBLIC_DEV_MENU=1 npx expo export --platform web && node scripts/serve-dist.js $PWD/dist 8081 &
//        NODE_PATH=$(npm root -g) node scripts/screenshots.js docs/screens   (needs Playwright + Chromium)
const { chromium } = require('playwright');
const OUT = process.argv[2] || '/home/user/memorypost-app/docs/screens';
const wait = (ms) => new Promise((r) => setTimeout(r, ms));
(async () => {
  const browser = await chromium.launch();
  const ctx = await browser.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, timezoneId: 'Asia/Seoul', locale: 'ko-KR', hasTouch: false });
  const page = await ctx.newPage();
  const logs = [];
  page.on('console', (m) => { if (m.type() === 'error' || m.type() === 'warning') logs.push(m.type() + ': ' + m.text()); });
  page.on('pageerror', (e) => logs.push('pageerror: ' + e.message));
  await page.goto('http://localhost:8081/');
  await page.evaluate(() => localStorage.clear());
  await page.reload();
  await wait(3500);
  const shot = async (name) => { await page.screenshot({ path: `${OUT}/${name}.png` }); console.log('shot', name); };
  const longPress = async (loc) => { const b = await loc.boundingBox(); await page.mouse.move(b.x + b.width / 2, b.y + b.height / 2); await page.mouse.down(); await wait(900); await page.mouse.up(); await wait(500); };
  const dateLoc = page.getByText(/\d+월 \d+일 .요일/).first();
  const dev = async (label) => { await longPress(dateLoc); await page.getByText(label, { exact: true }).last().click(); await wait(800); };
  // sample schedule on + day
  await longPress(dateLoc);
  await page.getByText('예시 일정 켜기', { exact: true }).click(); await wait(300);
  await page.getByText('오후', { exact: true }).last().click(); await wait(1200);
  await shot('01-home-day');
  await page.setViewportSize({ width: 390, height: 1900 }); await wait(800); await shot('01b-home-day-full'); await page.setViewportSize({ width: 390, height: 844 }); await wait(600);
  await dev('밤'); await wait(800);
  await shot('02-home-night');
  await dev('오후'); await wait(3000);
  await page.getByText('보내기', { exact: true }).first().click(); await wait(900);
  await shot('03-travel-sheet');
  await page.getByText(/차림으로 .* 보내기/).click(); await wait(1600);
  await shot('03b-depart');
  await wait(3000);
  await shot('03c-on-trip');
  await page.getByText('바로 도착', { exact: true }).click(); await wait(1200);
  await page.getByText('열어 보기', { exact: true }).click(); await wait(800);
  await shot('04a-envelope');
  await page.getByLabel('봉투 열기').click({ force: true }); await wait(1500);
  await shot('04-postcard-front');
  await page.getByText('뒷면 보기', { exact: true }).click(); await wait(1200);
  await shot('04b-postcard-back');
  await page.getByText('엽서함에 넣기', { exact: true }).click(); await wait(2500);
  await page.getByRole('tab', { name: '엽서함' }).click(); await wait(1200);
  await shot('05-album');
  await page.getByRole('tab', { name: '옷장' }).click(); await wait(1200);
  await shot('06-wardrobe');
  await page.getByRole('tab', { name: '친구들' }).click(); await wait(1200);
  await shot('07-friends');
  await page.getByText('4,400원', { exact: true }).first().click(); await wait(700);
  await shot('07b-store-sheet');
  await page.getByText('구매', { exact: true }).click(); await wait(300);
  await shot('07c-paying');
  await wait(1800);
  await shot('08-purchase-complete');
  await page.getByText('이제 같이 해 봐요!', { exact: true }).click(); await wait(1500);
  await shot('09-home-lion');
  await dev('2일 뒤'); await wait(1500);
  await shot('10-home-sad-2days');
  await page.getByRole('tab', { name: '친구들' }).click(); await wait(1000);
  await shot('11-friends-after');
  console.log(logs.slice(0, 30).join('\n'));
  await browser.close();
})().catch((e) => { console.error(e); process.exit(1); });
